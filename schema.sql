-- ---------- Tables ----------

CREATE TABLE utilisateur (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login             varchar(50)  NOT NULL UNIQUE,
    mot_de_passe_hash varchar(255) NOT NULL,
    sel               varchar(64)  NOT NULL,
    role              varchar(20)  NOT NULL CHECK (role IN ('ADMIN','EMPLOYE')),
    actif             boolean      NOT NULL DEFAULT true,
    cree_le           timestamp    NOT NULL DEFAULT now()
);

CREATE TABLE parcelle (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom          varchar(80)   NOT NULL UNIQUE,
    surface      numeric(10,2) NOT NULL CHECK (surface > 0),
    type_sol     varchar(40),
    localisation varchar(120)
);

CREATE TABLE culture (
    id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcelle_id         integer NOT NULL REFERENCES parcelle(id),
    nom                 varchar(60) NOT NULL,
    date_semis          date,
    statut              varchar(20) NOT NULL DEFAULT 'PLANIFIEE'
                        CHECK (statut IN ('PLANIFIEE','EN_COURS','RECOLTEE','ABANDONNEE')),
    date_recolte_prevue date
);

CREATE TABLE recolte (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    culture_id   integer NOT NULL REFERENCES culture(id),
    date_recolte date NOT NULL,
    quantite     numeric(10,2) NOT NULL CHECK (quantite > 0),
    unite        varchar(10) NOT NULL DEFAULT 'kg'
);

CREATE TABLE intervention (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parcelle_id integer NOT NULL REFERENCES parcelle(id),
    date_prevue date NOT NULL,
    type        varchar(40) NOT NULL
                CHECK (type IN ('Arrosage','Désherbage','Traitement','Récolte','Autre')),
    realisee    boolean NOT NULL DEFAULT false,
    notes       varchar(200)
);

-- ---------- Index sur les clés étrangères ----------

CREATE INDEX idx_culture_parcelle  ON culture(parcelle_id);
CREATE INDEX idx_recolte_culture   ON recolte(culture_id);
CREATE INDEX idx_intervention_parc ON intervention(parcelle_id);
CREATE INDEX idx_intervention_date ON intervention(date_prevue);

